#!/bin/sh
# Generate dist/systems/psxstock.games (metadata of the console's 20 built-in games) from
# a copy of the console's regional game database. The console has no sqlite, so the
# frontend reads this text file instead (docs/systems.md, layout = stock).
#   tools/make-stock-games.sh <regional.db> [out]     (default out: dist/systems/psxstock.games)
# Line format: id|title|publisher|year|players|basename1,basename2,...  (UTF-8)
# Titles and publishers are trimmed; the trademark signs (TM, R) are removed.
set -e
cd "$(dirname "$0")/.."
DB="$1"
OUT="${2:-dist/systems/psxstock.games}"
[ -f "$DB" ] || { echo "usage: $0 <regional.db> [out]"; exit 1; }
command -v sqlite3 > /dev/null || { echo "sqlite3 not found"; exit 1; }
TM=$(printf '\342\204\242')   # U+2122
RS=$(printf '\302\256')       # U+00AE
TMP="$OUT.tmp"
{
  echo "# Built-in PlayStation Classic games: id|title|publisher|year|players|discs"
  echo "# id = folder under the read-only game partition; discs = BASENAME of each disc, disc 1 first."
  echo "# Generated by tools/make-stock-games.sh; do not edit by hand."
  sqlite3 -separator '|' "$DB" "
    SELECT g.GAME_ID, trim(g.GAME_TITLE_STRING), trim(g.PUBLISHER_NAME), g.RELEASE_YEAR, g.PLAYERS,
           (SELECT group_concat(BASENAME, ',') FROM
              (SELECT BASENAME FROM DISC d WHERE d.GAME_ID = g.GAME_ID ORDER BY d.DISC_NUMBER))
    FROM GAME g ORDER BY g.GAME_ID;" |
  LC_ALL=C sed -e "s/$TM//g" -e "s/$RS//g" -e 's/ *| */|/g' -e 's/ *$//'
} > "$TMP"
mv "$TMP" "$OUT"
echo "$(grep -vc '^#' "$OUT") games -> $OUT"
